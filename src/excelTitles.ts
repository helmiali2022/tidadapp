export const cleanArabicString = (str: string | null | undefined): string => {
  if (!str) return "";
  return String(str)
    .normalize("NFC")
    .replace(/[\u200B-\u200D\uFEFF\u00A0]/g, "")
    .replace(/\s+/g, " ")
    .trim();
};

export const getExcelTitleForHeadName = (headName: string): string | null => {
  const cleaned = cleanArabicString(headName);
  if (!cleaned) return null;

  if (EXCEL_TITLE_MAPPINGS[cleaned]) {
    return EXCEL_TITLE_MAPPINGS[cleaned];
  }

  // Try matching without leading "عائلة " or "عيال "
  const withoutPrefix = cleaned.replace(/^(عائلة|عيال|بنات|أبناء|اولاد)\s+/, "");
  if (EXCEL_TITLE_MAPPINGS[withoutPrefix]) {
    return EXCEL_TITLE_MAPPINGS[withoutPrefix];
  }

  // Try matching against any key that is contained or matches
  for (const [key, title] of Object.entries(EXCEL_TITLE_MAPPINGS)) {
    if (cleaned === key || cleaned.includes(key) || key.includes(cleaned)) {
      return title;
    }
  }

  return null;
};
